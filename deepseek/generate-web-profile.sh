#!/usr/bin/env bash
# Regenerate the web profile's DSH settings from the model presets.
#
# The output, profile-patches/web.profile.cordis.patch.yml, is bind-mounted read-only over
# each DeepSeek service's web profile (see compose.ai.yml), so every service has the same
# providers, models and default model. DSH does not write it. Change models by editing the
# presets, rerunning this script, and restarting the DeepSeek containers.
#
# The only provider is the model broker, which serves every llama.cpp and Strata model
# behind one address and loads the one a request names.
set -euo pipefail

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
llama_file=${MODELS_PRESET_FILE:-"$script_dir/../llama-cpp/config/models-preset.ini"}
strata_file=${STRATA_PRESET_FILE:-"$script_dir/../strata/config/models-preset.ini"}
output_file=${1:-"$script_dir/profile-patches/web.profile.cordis.patch.yml"}
# The model a new session uses until another is chosen. It must be a broker model.
default_model=${DSH_DEFAULT_MODEL:-Qwen3.8-27B-UD-Q6_K_M--cuda0-cuda1}

for preset in "$llama_file" "$strata_file"; do
    if [[ ! -r $preset ]]; then
        echo "Cannot read preset: $preset" >&2
        exit 1
    fi
done

# Print "<model id>\t<context>" for every section of a preset, in file order, where the
# context is the section's value of $2 (ctx-size for llama.cpp; env.STRATA_CONTEXT for
# Strata, whose settings are the environment its container is started with).
model_contexts() {
    awk -v key="$2" '
        function finish() {
            if (name == "") return
            if (ctx !~ /^[1-9][0-9]*$/) {
                printf "Invalid or missing %s for %s\n", key, name > "/dev/stderr"
                bad = 1
                exit 1
            }
            printf "%s\t%s\n", name, ctx
        }
        /^\[/ {
            finish()
            name = substr($0, 2, length($0) - 2)
            ctx = ""
            next
        }
        {
            line = $0
            sub(/^[[:space:]]+/, "", line)
            if (index(line, key) == 1 && substr(line, length(key) + 1) ~ /^[[:space:]]*=/) {
                sub(/^[^=]*=[[:space:]]*/, "", line)
                ctx = line
            }
        }
        END {
            if (bad) exit 1
            if (name == "") {
                print "No model sections found" > "/dev/stderr"
                exit 1
            }
            finish()
        }
    ' "$1"
}

sorted_models() {
    LC_ALL=C sort --ignore-case --field-separator=$'\t' --key=1,1
}

models=$({
    model_contexts "$llama_file" ctx-size | sorted_models
    model_contexts "$strata_file" env.STRATA_CONTEXT | sorted_models
})

if ! cut -f1 <<<"$models" | grep -Fxq -- "$default_model"; then
    echo "DSH_DEFAULT_MODEL is not a broker model: $default_model" >&2
    exit 1
fi

tmp_file=$(mktemp "${output_file}.tmp.XXXXXX")
trap 'rm -f -- "$tmp_file"' EXIT

{
    printf '%s\n' \
        '# Generated by deepseek/generate-web-profile.sh; do not edit. Change the model presets' \
        '# and regenerate. Mounted read-only as the web profile'"'"'s cordis.patch.yml.' \
        '- id: ui-settings-general' \
        '  name: "@deepseek-ai/dsh-client-ui-settings-general"' \
        '  config:' \
        '    welcomeNoticeVersion: 2026-08-13.1' \
        '- id: llm-pi-ai' \
        '  name: "@deepseek-ai/dsh-llm-pi-ai"' \
        '  config:' \
        '    providers:' \
        '      # A model that is not loaded is loaded by the request for it, and the broker holds the' \
        '      # request until then, which for Strata can take most of an hour (its load timeout is' \
        '      # 3600 s), so the idle timeout is longer than that. The broker has no authentication' \
        '      # yet, so the key is a placeholder that only has to be non-empty.' \
        '      model-broker:' \
        '        apiKeyEnv: MODEL_BROKER_API_KEY' \
        '        api: openai-completions' \
        '        baseURL: http://model-broker:8000/v1' \
        '        streamIdleTimeoutMs: 3900000' \
        '        models:'
    awk -F '\t' '{ printf "          - id: %s\n            contextWindow: %s\n", $1, $2 }' <<<"$models"
    printf '%s\n' \
        '- id: agent-default-model' \
        '  name: "@deepseek-ai/dsh-agent-default-model"' \
        '  config:' \
        '    provider: model-broker' \
        "    model: $default_model"
} > "$tmp_file"

mv -- "$tmp_file" "$output_file"
